import { createHash } from 'node:crypto';
import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import tailwind from '@tailwindcss/vite';
import react from '@vitejs/plugin-react';
import { defineConfig, type Plugin } from 'vite';
import { thirdPartyNotices } from './build/notices.ts';

/** Where the site is published; used only for the absolute addresses social previews need. */
const SITE_URL = 'https://spl2dql.pages.dev';

/** The release version, shown in the About dialog. */
const VERSION = (JSON.parse(readFileSync(new URL('../../packages/cli/package.json', import.meta.url), 'utf8')) as { version: string }).version;

/**
 * Content-Security-Policy for the built app (dev needs inline scripts for hot reload, so build only).
 * The page never fetches anything (connect-src 'none'), and script addresses must come from the
 * app's own Trusted Types policy (lib/trusted.ts). The same constant goes into the <meta> tag and
 * into _headers, so the two cannot drift.
 */
const CSP = [
  "default-src 'self'",
  "script-src 'self'",
  "style-src 'self'",
  "img-src 'self' data:",
  "font-src 'self'",
  "connect-src 'none'",
  "worker-src 'self'",
  "manifest-src 'self'",
  "object-src 'none'",
  "base-uri 'none'",
  "form-action 'none'",
  "require-trusted-types-for 'script'",
  'trusted-types spl2dql',
].join('; ');

/** Headers for Cloudflare Pages (ADR-028): the set `spl2dql serve` sends, plus caching. */
function headersFile(): string {
  const all = [
    `Content-Security-Policy: ${CSP}; frame-ancestors 'none'`,
    'X-Content-Type-Options: nosniff',
    'X-Frame-Options: DENY',
    'Referrer-Policy: no-referrer',
    'Cross-Origin-Opener-Policy: same-origin',
    'Cross-Origin-Resource-Policy: same-origin',
    'Permissions-Policy: camera=(), microphone=(), geolocation=(), payment=(), usb=()',
    // The page, sw.js, the manifest and icons are checked with the host on every visit.
    'Cache-Control: no-cache',
  ];
  return `# Generated by apps/web/vite.config.ts from the same policy as the page's <meta> tag.
# Rules apply in order; "! Name" removes a header an earlier rule set.
/*
${all.map((h) => `  ${h}`).join('\n')}

# File names under /assets carry a content hash: they never change.
/assets/*
  ! Cache-Control
  Cache-Control: public, max-age=31536000, immutable

# The service worker fetches the app's own files to start offline; the page itself fetches nothing.
/sw.js
  ! Content-Security-Policy
  Content-Security-Policy: default-src 'none'; connect-src 'self'; frame-ancestors 'none'

# The link-preview picture is the one file other sites are meant to show.
/social.png
  ! Cross-Origin-Resource-Policy
  Cross-Origin-Resource-Policy: cross-origin
`;
}

const META_CSP = `<meta http-equiv="Content-Security-Policy" content="${CSP}">`;

function csp(): Plugin {
  return {
    name: 'spl2dql-csp',
    apply: 'build',
    transformIndexHtml(html) {
      return html.replace('<head>', `<head>\n    ${META_CSP}`);
    },
  };
}

/** Absolute addresses in the social preview tags. */
function siteUrl(): Plugin {
  return {
    name: 'spl2dql-site-url',
    transformIndexHtml(html) {
      return html.replaceAll('__SITE_URL__', SITE_URL);
    },
  };
}

/** Files in public/ the app needs to start offline and to be installed. */
const PUBLIC_PRECACHE = ['./manifest.webmanifest', './icon.svg', './icon-180.png', './icon-192.png', './icon-512.png'];

/**
 * Emits sw.js that precaches the build so the app starts with no connection (installable). It reads
 * and clears only its own caches (names starting with "spl2dql-"), so it leaves anything else on the
 * same origin alone.
 */
function serviceWorker(): Plugin {
  return {
    name: 'spl2dql-sw',
    apply: 'build',
    generateBundle(_options, bundle) {
      const assets = ['./', ...Object.keys(bundle).map((f) => `./${f}`), ...PUBLIC_PRECACHE].filter((f) => f !== './404.html' && f !== './_headers').sort();
      const version = createHash('sha256').update(assets.join('\n')).digest('hex').slice(0, 12);
      const source = `// Generated at build time. Precaches the app so it starts with no connection.
const CACHE = 'spl2dql-${version}';
const ASSETS = ${JSON.stringify(assets)};
// ignoreVary: a module script asks with an Origin header the precache request did not have.
const own = (request) => caches.open(CACHE).then((c) => c.match(request, { ignoreVary: true }));
self.addEventListener('install', (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(ASSETS)).then(() => self.skipWaiting()));
});
self.addEventListener('activate', (e) => {
  e.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith('spl2dql-') && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});
self.addEventListener('fetch', (e) => {
  const url = new URL(e.request.url);
  if (e.request.method !== 'GET' || url.origin !== self.location.origin) return;
  if (e.request.mode === 'navigate') {
    e.respondWith(fetch(e.request).catch(() => own('./')));
    return;
  }
  e.respondWith(own(e.request).then((hit) => hit || fetch(e.request)));
});
`;
      this.emitFile({ type: 'asset', fileName: 'sw.js', source });
    },
  };
}

/**
 * _headers for Cloudflare Pages and a 404 page in the look of the static shell. The 404 page can be
 * served at any depth, so it links its stylesheet from the site root.
 */
function hostFiles(): Plugin {
  return {
    name: 'spl2dql-host-files',
    apply: 'build',
    generateBundle(_options, bundle) {
      this.emitFile({ type: 'asset', fileName: '_headers', source: headersFile() });
      const css = Object.keys(bundle).find((f) => /^assets\/index-[\w-]+\.css$/.test(f));
      const page = `<!doctype html>
<html lang="en">
  <head>
    ${META_CSP}
    <meta charset="utf-8">
    <meta name="viewport" content="width=device-width, initial-scale=1">
    <meta name="referrer" content="no-referrer">
    <meta name="color-scheme" content="light dark">
    <meta name="robots" content="noindex">
    <title>Page not found – spl2dql</title>
    <link rel="icon" href="/icon.svg" type="image/svg+xml">
    ${css ? `<link rel="stylesheet" href="/${css}">` : ''}
  </head>
  <body>
    <div class="flex h-full flex-col">
      <header class="app-header">
        <p class="app-name">spl2dql</p>
        <p class="app-line">Translates Splunk searches to Dynatrace DQL, dashboards included.</p>
      </header>
      <main class="min-h-0 flex-1 px-4 py-6">
        <h1 class="text-lg font-semibold">Page not found</h1>
        <p class="mt-1 text-sm">There is nothing at this address.</p>
        <p class="mt-4"><a class="control primary" href="/">Open the translator</a></p>
      </main>
    </div>
  </body>
</html>
`;
      this.emitFile({ type: 'asset', fileName: '404.html', source: page });
    },
  };
}

export default defineConfig({
  base: './',
  plugins: [react(), tailwind(), siteUrl(), csp(), serviceWorker(), hostFiles(), thirdPartyNotices()],
  define: { __APP_VERSION__: JSON.stringify(VERSION) },
  resolve: {
    alias: { '@spl2dql/core': fileURLToPath(new URL('../../packages/core/src/index.ts', import.meta.url)) },
  },
  build: {
    target: 'es2022',
    modulePreload: { polyfill: false },
    assetsInlineLimit: 0,
    sourcemap: false,
    chunkSizeWarningLimit: 900,
  },
  worker: { format: 'es' },
  server: { host: '127.0.0.1', port: 5173 },
  preview: { host: '127.0.0.1' },
});

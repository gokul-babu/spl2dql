/**
 * Generates packages/core/src/dql/catalog.generated.ts from the vendored Apache-2.0 DQL reference in
 * third_party/dynatrace-for-ai/dql. Run with `pnpm gen:catalog`. The output is committed.
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const refDir = join(root, 'third_party/dynatrace-for-ai/dql');
const outFile = join(root, 'packages/core/src/dql/catalog.generated.ts');

interface Entry {
  named: Set<string>;
  positional: number;
}

function parseFile(text: string): Map<string, Entry> {
  const out = new Map<string, Entry>();
  let current: Entry | undefined;
  for (const line of text.split('\n')) {
    const heading = /^## `([A-Za-z][A-Za-z0-9]*)`/.exec(line);
    if (heading?.[1]) {
      current = { named: new Set(), positional: 0 };
      out.set(heading[1], current);
      continue;
    }
    if (!current) continue;
    // Signature line, e.g. `summarize aggregation, … [, by: { [expression, …] }]`
    if (/^`[^`]+`\s*$/.test(line.trim()) && !line.startsWith('  ')) {
      for (const m of line.matchAll(/([A-Za-z][A-Za-z0-9]*):/g)) if (m[1]) current.named.add(m[1]);
      continue;
    }
    // Parameter line, e.g.   `from:?` (Duration|…) — …
    const param = /^ {2}`([A-Za-z][A-Za-z0-9]*)(:)?(\*)?(\?)?`/.exec(line);
    if (param?.[1]) {
      if (param[2]) current.named.add(param[1]);
      else current.positional += 1;
    }
  }
  return out;
}

const files = readdirSync(refDir)
  .filter((f) => f.endsWith('.md'))
  .sort();
const commands = parseFile(readFileSync(join(refDir, 'dql-commands.md'), 'utf8'));
const functions = new Map<string, Entry>();
for (const f of files) {
  if (!f.startsWith('dql-functions-')) continue;
  for (const [name, entry] of parseFile(readFileSync(join(refDir, f), 'utf8'))) {
    const prev = functions.get(name);
    if (prev) for (const n of entry.named) prev.named.add(n);
    else functions.set(name, entry);
  }
}

function emit(map: Map<string, Entry>): string {
  return [...map.keys()]
    .sort()
    .map((name) => {
      const named = [...(map.get(name)?.named ?? [])].sort().map((n) => `'${n}'`);
      return `  ${name}: [${named.join(', ')}],`;
    })
    .join('\n');
}

const header = `// Generated by scripts/gen-dql-catalog.ts from third_party/dynatrace-for-ai/dql (Apache-2.0).
// Do not edit by hand. Regenerate with \`pnpm gen:catalog\`.
// Each entry maps a name to the named parameters the reference documents for it.
`;
writeFileSync(
  outFile,
  `${header}
// Null-prototype tables: names from untrusted DQL never resolve to Object.prototype members.
export const DQL_COMMANDS: Readonly<Record<string, readonly string[]>> = Object.freeze(Object.assign(Object.create(null), {
${emit(commands)}
}));

export const DQL_FUNCTIONS: Readonly<Record<string, readonly string[]>> = Object.freeze(Object.assign(Object.create(null), {
${emit(functions)}
}));
`,
);
console.log(`catalog: ${commands.size} commands, ${functions.size} functions → ${outFile}`);
